// Add function
function add(a, b) {
  return a + b;
}

console.log(add(7, 8));

// Subtract function
function subtract(a, b) {
  return a - b;
}

console.log(subtract(7, 8));

// Multiply function
function multiply(a, b) {
  return a * b;
}

console.log(multiply(7, 8));

// Divide function
function divide(a, b) {
  return a / b;
}

console.log(divide(7, 8));
